function loadData(){
  try{
    const raw = localStorage.getItem(STORAGE_KEY);
    let d = raw ? JSON.parse(raw) : JSON.parse(JSON.stringify(SAMPLE_DATA));
    d = migrateToPages(d);
    saveData(d);
    return d;
  }catch(e){ return migrateToPages(JSON.parse(JSON.stringify(SAMPLE_DATA))); }
}
/* Old data shape had book.questions directly. If we find that, wrap it into a single Page 1
   so nobody's existing questions get lost when this update rolls out. */
function migrateToPages(d){
  if(!d || !Array.isArray(d.books)) return JSON.parse(JSON.stringify(SAMPLE_DATA));
  d.books.forEach(b=>{
    if(!Array.isArray(b.pages)){
      const oldQuestions = Array.isArray(b.questions) ? b.questions : [];
      b.pages = oldQuestions.length ? [{ id:uid('pg'), number:1, questions:oldQuestions }] : [];
      delete b.questions;
    }
  });
  return d;
}
function saveData(d){ localStorage.setItem(STORAGE_KEY, JSON.stringify(d)); }
